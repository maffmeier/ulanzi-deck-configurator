#!/bin/sh
# Regenerates the Go module section of THIRD_PARTY_NOTICES.md from the
# modules linked into the binaries of all three platforms:
#   docker compose run --rm dev sh scripts/notices.sh
set -eu
cd "$(dirname "$0")/.."
begin='<!-- go-modules:begin -->'
end='<!-- go-modules:end -->'
tmp=$(mktemp)
trap 'rm -f "$tmp" "$tmp.mods"' EXIT

for os in linux windows darwin; do
  GOOS=$os go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}' ./cmd/ulanzi-deck
done | sort -u > "$tmp.mods"

{
  echo "$begin"
  echo
  echo "Go modules"
  echo "----------"
  echo
  echo "The binaries contain these Go modules (generated by scripts/notices.sh)."
  while read -r path version dir; do
    license=$(ls "$dir" | grep -iE '^(license|licence|copying)(\.(md|txt))?$' | head -n 1 || true)
    echo
    echo
    echo "### $path $version"
    echo
    if [ -n "$license" ]; then
      echo '```text'
      cat "$dir/$license"
      echo '```'
    else
      echo "(no license file in the module)"
    fi
  done < "$tmp.mods"
  echo
  echo "$end"
} > "$tmp"

if grep -q "$begin" THIRD_PARTY_NOTICES.md; then
  awk -v b="$begin" -v e="$end" -v f="$tmp" '
    $0 == b { while ((getline line < f) > 0) print line; skip = 1; next }
    $0 == e { skip = 0; next }
    !skip { print }
  ' THIRD_PARTY_NOTICES.md > "$tmp.new"
  mv "$tmp.new" THIRD_PARTY_NOTICES.md
else
  { echo; echo; cat "$tmp"; } >> THIRD_PARTY_NOTICES.md
fi
echo "THIRD_PARTY_NOTICES.md: $(wc -l < "$tmp.mods") modules"
